/*
**  innd's C++ state for the article being received on a channel
**  (CONVERSION_NOTES.md, "innd's in-memory article").
**
**  ARTDATA stays a C struct, because innd.h is also compiled as C by the
**  tests and chan.cc copies channels as plain structs; it holds a pointer
**  to an ArticleState, which C code sees as an incomplete type.  Each
**  channel owns one: CHANcreate creates it (or keeps the one the slot
**  already has) and CHANclose deletes it.  ARTprepare calls clear() before
**  each article.  The fields move here from ARTDATA in later steps.
*/

#ifndef INND_ARTICLE_H
#define INND_ARTICLE_H 1

#include <string>
#include <string_view>

struct ArticleState {
    ArticleState() = default;
    ArticleState(const ArticleState &) = delete;
    ArticleState &operator=(const ArticleState &) = delete;

    /* The generated Xref header field body, "<host> group:num ...", folded
       if long, with its trailing CRLF (ARTassignnumbers). */
    std::string xref;

    /* The group:num list: in xref, or in the received Xref header field in
       xrefslave mode (ARTxrefslave).  Without a trailing CRLF. */
    std::string_view replic;

    /* The generated Bytes header field, "Bytes: <n>\r\n" (ARTstore). */
    std::string bytes;

    /* The Lines value for overview (ARTmakeoverview). */
    std::string lines;

    /* The digits of the Bytes header field. */
    std::string_view
    bytes_value() const
    {
        constexpr std::string_view prefix = "Bytes: ";
        if (bytes.size() < prefix.size() + 2)
            return {};
        return std::string_view(bytes).substr(
            prefix.size(), bytes.size() - prefix.size() - 2);
    }

    /* Reset for the next article on the channel.  The strings keep their
       capacity, as the buffers they replace were reused. */
    void
    clear()
    {
        xref.clear();
        replic = {};
        bytes.clear();
        lines.clear();
    }
};

#endif /* !INND_ARTICLE_H */
